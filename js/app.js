/* ===================== build grid ===================== */

function buildGrid() {
  const words = [...VOCAB_DATA.words].sort((a, b) => a.order - b.order);
  document.getElementById('wordCount').textContent = words.length + '개 어휘';

  words.forEach((w) => {
    const card = document.createElement('button');
    card.className = 'card';
    card.type = 'button';
    card.setAttribute('role', 'listitem');
    card.setAttribute('aria-label', w.ko.word + ' 학습하기');
    card.innerHTML = `
      <span class="num">${String(w.order).padStart(2, '0')}</span>
      <span class="icon">${ICONS[w.icon] || ICONS.book}</span>
      <span class="word">${w.ko.word}</span>
      <span class="hint">
        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M11 5L6 9H3v6h3l5 4V5z"/><path d="M15.5 8.5a5 5 0 0 1 0 7"/></svg>
        눌러서 듣기
      </span>
    `;
    card.addEventListener('click', () => openDetail(w));
    grid.appendChild(card);
  });
}

