/* ===================== open / close ===================== */

function openDetail(word) {
  currentWord = word;
  currentLang = 'ko';
  hasRevealedFlags = false;

  flagsWrap.classList.remove('is-shown');
  flagsCaption.style.opacity = 0;
  Object.values(FLAG_BTNS).forEach((b) => b.classList.remove('is-active'));

  unitTag.textContent = word.ko.word + ' · 사회 개념어';

  detail.classList.add('is-visible');
  detail.setAttribute('aria-hidden', 'false');
  document.body.classList.add('detail-open');
  detail.scrollTop = 0;

  renderLang('ko');
  playCurrent();
}

function closeDetail() {
  detail.classList.remove('is-visible');
  detail.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('detail-open');
  player.pause();
  player.currentTime = 0;
  replayBtn.classList.remove('is-playing');
}

closeBtn.addEventListener('click', closeDetail);
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && detail.classList.contains('is-visible')) closeDetail();
});

/* ===================== render language content ===================== */

function renderLang(lang) {
  const entry = currentWord[lang];
  currentLang = lang;

  wordDisplay.textContent = entry.word;
  wordDisplay.setAttribute('lang', lang);

  wordImage.src = `assets/images/${currentWord.slug}.jpg`;
  wordImage.alt = entry.word + ' 의미를 보여주는 그림';

  descText.textContent = entry.desc;
  descText.setAttribute('lang', lang);

  examplesList.innerHTML = '';
  (entry.examples || []).forEach((ex) => {
    const li = document.createElement('li');
    li.textContent = ex;
    examplesList.appendChild(li);
  });
  examplesList.setAttribute('lang', lang);

  const toggleLabels = {
    ko: '생활 속 예시 더 보기',
    en: 'See more real-life examples',
    ru: 'Показать больше примеров',
    zh: '查看更多生活实例'
  };
  examplesToggleLabel.textContent = toggleLabels[lang] || toggleLabels.ko;

  Object.entries(FLAG_BTNS).forEach(([lg, btn]) => {
    btn.classList.toggle('is-active', lg === lang);
  });
}

function setLang(lang, opts = {}) {
  renderLang(lang);
  playCurrent();
}

/* ===================== audio playback ===================== */

function playCurrent() {
  if (!currentWord) return;
  const src = `assets/audio/${currentWord.slug}_${currentLang}.m4a`;
  player.pause();
  player.src = src;
  player.currentTime = 0;
  const playPromise = player.play();
  if (playPromise && playPromise.catch) {
    playPromise.catch(() => { /* autoplay may be blocked until user interacts once; ignore */ });
  }
  replayBtn.classList.add('is-playing');
}

replayBtn.addEventListener('click', playCurrent);

player.addEventListener('timeupdate', () => {
  if (!player.duration) return;
  progressFill.style.width = ((player.currentTime / player.duration) * 100).toFixed(1) + '%';
});

player.addEventListener('ended', () => {
  progressFill.style.width = '0%';
  replayBtn.classList.remove('is-playing');

  if (currentLang === 'ko' && !hasRevealedFlags) {
    hasRevealedFlags = true;
    flagsWrap.classList.add('is-shown');
    setTimeout(() => { flagsCaption.style.opacity = 0; }, 3200);
  }
});

